export function testsForRegions(regionIds: RegionId[]): OrthopedicTest[] {
  const seen = new Set<string>();
  const list: OrthopedicTest[] = [];
  for (const regionId of regionIds) {
    let count = 0;
    for (const test of TESTS) {
      if (test.regionId !== regionId || seen.has(test.id)) continue;
      list.push(test);
      seen.add(test.id);
      count += 1;
      if (count >= 2) break;
    }
  }
  return list;
}
